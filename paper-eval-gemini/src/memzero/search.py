"""Search and answer stage, as in the paper's search.py, with three changes:
  1. local Mem0 (Gemini + Qdrant + Kuzu) instead of the hosted MemoryClient
  2. answers generated by Gemini on Vertex AI instead of OpenAI
  3. crash safety: resumes from the saved file, retries with backoff, saves atomically
"""
import json
import os
import time
from collections import defaultdict

from dotenv import load_dotenv
from google import genai
from google.genai import types
from jinja2 import Template
from prompts import ANSWER_PROMPT, ANSWER_PROMPT_GRAPH
from tqdm import tqdm

from src.memzero.config import get_memory

load_dotenv()


def with_backoff(fn, what, tries=8):
    for attempt in range(tries):
        try:
            return fn()
        except Exception as e:
            if attempt == tries - 1:
                raise
            wait = min(120, 2 ** (attempt + 1))
            print(f"[retry] {what}: {type(e).__name__}: {str(e)[:120]} -> sleeping {wait}s", flush=True)
            time.sleep(wait)


class MemorySearch:
    def __init__(self, output_path="results.json", top_k=10, filter_memories=False, is_graph=False):
        self.memory = get_memory(is_graph)
        self.client = genai.Client()  # Vertex AI via environment variables
        self.model = os.getenv("MODEL", "gemini-2.5-flash-lite")
        self.top_k = top_k
        self.results = defaultdict(list)
        self.output_path = output_path
        self.filter_memories = filter_memories
        self.is_graph = is_graph
        self.ANSWER_PROMPT = ANSWER_PROMPT_GRAPH if is_graph else ANSWER_PROMPT

        # Resume: keep every question already answered in a previous (interrupted) run
        if os.path.exists(output_path):
            with open(output_path) as f:
                previous = json.load(f)
            for key, rows in previous.items():
                self.results[int(key)] = rows
            print(f"[resume] {sum(len(v) for v in self.results.values())} questions already answered", flush=True)

    def save(self):
        tmp = self.output_path + ".tmp"
        with open(tmp, "w") as f:
            json.dump(self.results, f, indent=4)
        os.replace(tmp, self.output_path)  # atomic: the file is never half-written

    def search_memory(self, user_id, query):
        def _search():
            t0 = time.time()
            res = self.memory.search(query, user_id=user_id, limit=self.top_k)
            return res, time.time() - t0  # time of the successful attempt only

        memories, elapsed = with_backoff(_search, f"search {user_id}")
        semantic_memories = [
            {
                "memory": m["memory"],
                "timestamp": m["metadata"]["timestamp"],
                "score": round(m["score"], 2),
            }
            for m in memories.get("results", [])
        ]
        graph_memories = None
        if self.is_graph:
            graph_memories = [
                {
                    "source": r.get("source"),
                    "relationship": r.get("relationship"),
                    "target": r.get("target", r.get("destination")),
                }
                for r in memories.get("relations", [])[:5]
            ]
        return semantic_memories, graph_memories, elapsed

    def answer_question(self, speaker_1_user_id, speaker_2_user_id, question, answer, category):
        speaker_1_memories, speaker_1_graph_memories, speaker_1_memory_time = self.search_memory(
            speaker_1_user_id, question
        )
        speaker_2_memories, speaker_2_graph_memories, speaker_2_memory_time = self.search_memory(
            speaker_2_user_id, question
        )

        search_1_memory = [f"{item['timestamp']}: {item['memory']}" for item in speaker_1_memories]
        search_2_memory = [f"{item['timestamp']}: {item['memory']}" for item in speaker_2_memories]

        answer_prompt = Template(self.ANSWER_PROMPT).render(
            speaker_1_user_id=speaker_1_user_id.split("_")[0],
            speaker_2_user_id=speaker_2_user_id.split("_")[0],
            speaker_1_memories=json.dumps(search_1_memory, indent=4),
            speaker_2_memories=json.dumps(search_2_memory, indent=4),
            speaker_1_graph_memories=json.dumps(speaker_1_graph_memories, indent=4),
            speaker_2_graph_memories=json.dumps(speaker_2_graph_memories, indent=4),
            question=question,
        )

        def _answer():
            t1 = time.time()
            resp = self.client.models.generate_content(
                model=self.model,
                contents=answer_prompt,
                config=types.GenerateContentConfig(temperature=0.0),
            )
            return (resp.text or ""), time.time() - t1

        response, response_time = with_backoff(_answer, "answer")
        return (
            response,
            speaker_1_memories,
            speaker_2_memories,
            speaker_1_memory_time,
            speaker_2_memory_time,
            speaker_1_graph_memories,
            speaker_2_graph_memories,
            response_time,
        )

    def process_question(self, val, speaker_a_user_id, speaker_b_user_id):
        question = val.get("question", "")
        answer = val.get("answer", "")
        category = val.get("category", -1)
        (
            response,
            speaker_1_memories,
            speaker_2_memories,
            speaker_1_memory_time,
            speaker_2_memory_time,
            speaker_1_graph_memories,
            speaker_2_graph_memories,
            response_time,
        ) = self.answer_question(speaker_a_user_id, speaker_b_user_id, question, answer, category)
        return {
            "question": question,
            "answer": answer,
            "category": category,
            "evidence": val.get("evidence", []),
            "response": response,
            "adversarial_answer": val.get("adversarial_answer", ""),
            "speaker_1_memories": speaker_1_memories,
            "speaker_2_memories": speaker_2_memories,
            "num_speaker_1_memories": len(speaker_1_memories),
            "num_speaker_2_memories": len(speaker_2_memories),
            "speaker_1_memory_time": speaker_1_memory_time,
            "speaker_2_memory_time": speaker_2_memory_time,
            "speaker_1_graph_memories": speaker_1_graph_memories,
            "speaker_2_graph_memories": speaker_2_graph_memories,
            "response_time": response_time,
        }

    def process_data_file(self, file_path):
        with open(file_path) as f:
            data = json.load(f)

        for idx, item in tqdm(enumerate(data), total=len(data), desc="Processing conversations"):
            conversation = item["conversation"]
            speaker_a_user_id = f"{conversation['speaker_a']}_{idx}"
            speaker_b_user_id = f"{conversation['speaker_b']}_{idx}"
            already = len(self.results[idx])  # questions are answered in order, so skip the first `already`

            for q_i, question_item in enumerate(
                tqdm(item["qa"], desc=f"Processing questions for conversation {idx}", leave=False)
            ):
                if q_i < already:
                    continue
                self.results[idx].append(self.process_question(question_item, speaker_a_user_id, speaker_b_user_id))
                self.save()

        self.save()
        print("Search finished", flush=True)
